const listeners = new Set();
let currentLanguage = "en";

export function normalizeLanguage(stored, navigatorLanguage = "en") {
  if (stored === "tr" || stored === "en") return stored;
  return String(navigatorLanguage || "en").toLowerCase().startsWith("tr") ? "tr" : "en";
}

export function getLanguage() {
  return currentLanguage;
}

export function t(key, vars = {}) {
  const table = messages[currentLanguage] || messages.en;
  let text = table[key] ?? messages.en[key] ?? key;
  Object.entries(vars).forEach(([name, value]) => {
    text = text.replaceAll(`{${name}}`, String(value));
  });
  return text;
}

export function onLanguageChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

function readStoredLanguage() {
  try {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY);
  } catch {
    return null;
  }
}

export function detectLanguage() {
  return normalizeLanguage(readStoredLanguage(), globalThis.navigator?.language);
}

export function applyI18n(root = globalThis.document) {
  if (!root?.querySelectorAll) return;
  const lang = currentLanguage;
  if (root.documentElement) root.documentElement.lang = lang;
  const titleKey = root.documentElement?.getAttribute("data-i18n-document-title");
  if (titleKey && root.title != null) root.title = t(titleKey);

  root.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (key) element.textContent = t(key);
  });
  root.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.getAttribute("data-i18n-html");
    if (key) element.innerHTML = t(key);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", t(element.getAttribute("data-i18n-aria")));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((element) => {
    element.setAttribute("title", t(element.getAttribute("data-i18n-title")));
  });
  root.querySelectorAll("[data-set-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", button.getAttribute("data-set-lang") === lang ? "true" : "false");
  });
  const group = root.querySelector?.(".lang-switch");
  if (group) group.setAttribute("aria-label", t("lang.group"));
}

export function setLanguage(language) {
  const next = language === "tr" ? "tr" : "en";
  currentLanguage = next;
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
  } catch {
    /* private mode */
  }
  applyI18n();
  listeners.forEach((listener) => listener(next));
}

export function startI18n() {
  currentLanguage = detectLanguage();
  applyI18n();
  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    if (button.dataset.langBound === "true") return;
    button.dataset.langBound = "true";
    button.addEventListener("click", () => setLanguage(button.getAttribute("data-set-lang")));
  });
}
